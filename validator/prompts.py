SYSTEM = f"""\
Ты ведущий аналитик требований и QA-инженер банка. Ты проводишь статическое ревью документа с требованиями \
до начала разработки по ISO/IEC/IEEE 29148:2018 (п. 5.2.5, 5.2.6) и IEEE Std 830-1998 (п. 4.3). \
Ты ищешь дефекты формулировок: неоднозначность, непроверяемость, противоречия, пропуски, лишние проектные решения.

Правила работы:
1. Опирайся только на текст документа. Не придумывай факты о системе и не додумывай за автора.
2. Цитаты копируй из документа дословно, символ в символ, без номеров строк и разметки, 3-30 слов. \
Цитата должна однозначно указывать место. Если дефект в отсутствии чего-то, цитируй место, где это должно было быть.
3. Будь конкретен. Каждое нарушение объясняет, что именно не так, и показывает это на примере: два возможных \
толкования, сценарий, который документ не покрывает, или расчёт, который не сходится. Общие фразы \
(«требование можно улучшить», «следует уточнить детали») запрещены.
4. Предлагай исправление: готовую формулировку требования или что именно добавить.
5. Одно и то же нарушение не дублируй под разными критериями: выбери самый точный.
6. Значения вида [КАРТА_1], [ФИО_1] это замаскированные данные. Это не дефект документа.
7. Ссылаясь на место в документе, пиши «строка N» (номера в документе это строки, а не страницы).
8. Пиши по-русски, деловым языком. Не используй длинные тире, используй двоеточие, запятую или скобки.

Шкала серьёзности:
{SEVERITY_RULES}

Что особенно проверять в финтех-требованиях:
- Деньги: единицы (тенге/тиыны), округление, валюта карты и операции, курс конвертации, комиссии.
- Время: часовой пояс, граница суток и месяца, дата совершения операции против даты проведения (авторизация и клиринг).
- Жизненный цикл операции: авторизация, проведение, отмена, частичный и полный возврат, повторная доставка и порядок \
событий, идемпотентность.
- Пороги: включительно или нет, тип числа, поведение на границе, изменение настройки посреди периода.
- Уведомления: канал, текст, что если push не доставлен или отключён на устройстве, дубли, частота.
- Безопасность и персональные данные: аутентификация, проверка владельца ресурса, маскирование номера карты, данные в URL и логах.
- API: метод HTTP и его семантика, коды ответа и их тела, согласованность типов, обработка ошибок валидации.
- Статусы карты (активна, заблокирована, перевыпущена), несколько карт у клиента.
- НФТ: метрика, перцентиль, точка начала и конца измерения, нагрузка; доступность; мониторинг; откат.
- Тестируемость: критерии приёмки для каждого функционального требования, граничные и негативные сценарии.
"""


def segmentation(numbered_doc: str) -> str:
    return f"""\
Задача: выдели из документа все отдельные требования, которые будем проверять.

Требование это утверждение о том, что система, процесс, интерфейс или данные должны делать или какими быть. \
Включай:
- цели и бизнес-требования;
- функциональные требования (каждый пункт с номером отдельно, составной пункт не дроби, а бери целиком);
- нефункциональные требования, требования к данным, к интеграции;
- описания архитектуры, UI, BPMN и sequence, если в них есть обязательства системы;
- шаги логики метода API, особые правила, общие параметры метода (метод HTTP, URL, авторизация вместе одной записью);
- каждую строку таблицы параметров запроса отдельно; таблицу параметров ответа одной записью; каждый код ответа \
со своим описанием и примером отдельно;
- каждую строку таблицы критериев приёмки отдельно.

Не включай (перечисли в skipped с причиной): метаданные (наименование задачи, JIRA, роли), чек-листы ревью, \
блок согласующих, пояснения о самом документе, пустые разделы и разделы с заглушкой.

Для каждого требования:
- doc_id: идентификатор из документа (например «Ф-1»). Если номера нет, построй понятный локатор: \
«A. НФТ», «B. Логика п. 5», «B. Параметр amount», «A. Критерий приёмки 2», «B. Статус 403».
- section: раздел документа.
- quote: дословная цитата требования одним непрерывным куском из одного места документа (для длинного пункта первые \
1-2 предложения, для строки таблицы её ключевые ячейки в том виде, как они записаны). Не склеивай фрагменты из разных \
строк: если требование описано в нескольких местах, цитируй самое характерное.
- summary: суть требования до 15 слов.
- kind: functional | nonfunctional | data | integration | interface | api | acceptance | business | constraint.

Сохраняй порядок документа. Ничего не пропускай: лучше лишняя запись, чем потерянное требование.

Документ (номер строки | текст):
<document>
{numbered_doc}
</document>
"""


def requirement_review(numbered_doc: str, batch: list[dict]) -> str:
    items = "\n".join(
        f"- {r['rid']} (в документе: {r['doc_id']}; раздел: {r['section']}; строки {r['lines']}): «{r['quote']}»"
        for r in batch
    )
    return f"""\
Задача: проверь каждое требование из списка ниже по всем критериям отдельного требования.

Критерии (коды):
{criteria_block(REQUIREMENT_CRITERIA)}

Для каждого требования верни:
- verdicts: по одному на каждый из 9 критериев: verdict = ok | violation | na, comment = короткое обоснование \
(до 25 слов) с привязкой к тексту.
- findings: по одной записи на каждый конкретный дефект (criterion, severity, quotes, problem, fix). \
Если verdict = violation, должна быть хотя бы одна находка с этим критерием.

Учитывай весь документ: если требование противоречит критериям приёмки, схемам, разделу данных или дочерней \
спецификации, это нарушение критерия correct этого требования, и в quotes нужны обе стороны противоречия. \
Проверяй арифметику и даты в примерах. Не ставь violation ради формы: только если можешь показать проблему на тексте.
Если один и тот же дефект касается нескольких требований из списка, запиши его один раз: у того требования, где он \
проявляется явнее, а в verdicts остальных сошлись на это требование в comment.

Требования для проверки:
{items}

Документ целиком (номер строки | текст):
<document>
{numbered_doc}
</document>
"""


def set_consistency(numbered_doc: str, req_table: str, known: str) -> str:
    return f"""\
Задача: проверь набор требований целиком на непротиворечивость (set_consistent) и корректность связей.

Пройди систематически:
1. Каждый критерий приёмки против функциональных требований: подставь значения, посчитай, сверь даты и часовые \
пояса. Совпадает ли ожидаемый результат с тем, что следует из требований?
2. Функциональные требования попарно: нет ли правил, которые в каком-то сценарии требуют противоположного \
(ограничение против исключения из него, значение по умолчанию против явного правила, два правила для одного события)?
3. Цели и НФТ против функциональных требований и источника событий: выполнимы ли обещания по срокам и моменту \
срабатывания, если учесть, когда система реально получает событие.
4. Часть с бизнес-требованиями против дочерней спецификации API: все ли операции, на которые ссылается основная \
часть, описаны в API; те ли поля, типы, единицы, границы, коды ответа и их смысл.
5. Внутри спецификации API: описание против метода HTTP, заголовок статуса против тела, перечень кодов против \
реально возвращаемых, типы в запросе против типов в ответе.
6. UI и раздел данных против API: всё ли, что показывает экран, можно получить; все ли хранимые поля согласованы по единицам.
7. Термины: одно понятие под разными названиями или одно название для разных понятий.

Каждое противоречие это отдельная находка: criterion = set_consistent (или set_complete, если одна сторона \
просто отсутствует), req_ids = затронутые ТР, quotes = обе стороны противоречия дословно.

Эти дефекты уже найдены автоматическими правилами, не повторяй их:
{known}

Требования (ID отчёта | ID в документе | строки | суть):
{req_table}

Для verdicts верни оценку только по критерию set_consistent.

Документ (номер строки | текст):
<document>
{numbered_doc}
</document>
"""


def set_completeness(numbered_doc: str, req_table: str, known: str) -> str:
    return f"""\
Задача: проверь набор требований целиком по критериям набора, кроме непротиворечивости.

Критерии набора (коды):
{criteria_block([c for c in SET_CRITERIA if c.code != "set_consistent"])}

Пройди систематически:
1. Покрытие критериями приёмки: для каждого функционального требования есть ли критерий приёмки? Каких сценариев \
не хватает (границы диапазона, повтор, возврат, смена настройки, выключенное уведомление, ошибки)?
2. Пропущенные сценарии и требования: что разработчик или тестировщик спросит первым, а в документе ответа нет \
(по чек-листу финтех-рисков из инструкции).
3. Пустые и шаблонные разделы, отсутствующие НФТ (доступность, безопасность, журналирование, хранение данных).
4. Выполнимость: хватает ли данных и событий из описанных интеграций, чтобы выполнить требования.
5. Валидируемость: измерима ли цель, понятно ли, как подтвердить пользу.
6. Прослеживаемость, ранжирование, модифицируемость: идентификаторы, связи между целью, требованием и проверкой, \
приоритеты, версия, согласование, дублирование правил между частями.

Каждый дефект это отдельная находка. Для пропуска цитируй место, куда должно быть добавлено требование \
(раздел или соседнее требование), и прямо пиши, какого сценария не хватает и почему это важно.

Эти дефекты уже найдены автоматическими правилами, не повторяй их:
{known}

Требования (ID отчёта | ID в документе | строки | суть):
{req_table}

Для verdicts верни оценку по каждому из 7 критериев: ok | partial | violation.

Документ (номер строки | текст):
<document>
{numbered_doc}
</document>
"""


def verification(numbered_doc: str, findings_block: str) -> str:
    return f"""\
Задача: ты независимый рецензент. Проверь находки другого ревьюера и правил. Для каждой находки реши:
- keep = true, если дефект действительно есть в тексте документа, описан конкретно и привязан к цитате;
- keep = false, если находка основана на неверном прочтении документа, на домысле (документ на самом деле \
отвечает на вопрос в другом месте), слишком общая, или это не дефект требований;
- severity: откалибруй по шкале серьёзности (повышай, если дефект блокирует разработку или тесты; понижай \
за оформление);
- duplicate_of: если находка описывает тот же дефект, что и другая, укажи ID той, что описана полнее \
(у оставшейся duplicate_of пустой). Дубль тоже keep = true, но с заполненным duplicate_of.
- reason: одно предложение.

Будь строг к домыслам, но не отбрасывай реальные дефекты только потому, что они кажутся мелкими.
Верни решение для каждой находки, ни одну не пропускай.

Находки:
{findings_block}

Документ (номер строки | текст):
<document>
{numbered_doc}
</document>
"""


def deduplication(findings_block: str) -> str:
    return f"""\
Задача: найди среди подтверждённых находок дубли, то есть группы находок про один и тот же дефект документа.

Находки дублируют друг друга, если у них одна причина и их закрывает одно исправление документа, даже если они \
привязаны к разным требованиям, разным критериям или цитируют разные строки (например, одно противоречие, \
описанное со стороны каждого из двух требований).
Не объединяй разные дефекты только потому, что они находятся в одном месте или касаются одного требования.

Для каждой группы:
- keep: ID основной находки (самая полная и точная формулировка; при равенстве более серьёзная);
- duplicates: ID остальных находок группы;
- reason: одно предложение, в чём общий дефект.
Находки без дублей не перечисляй.

Находки (отсортированы по месту в документе):
{findings_block}
"""


def clarification(numbered_doc: str, findings_block: str) -> str:
    return f"""\
Задача: подготовь вопросы для уточнения, которые аналитик должен задать заказчику и смежным командам до старта \
разработки. На основе подтверждённых дефектов ниже.

Требования к вопросам:
- Задавай вопрос только если ответ меняет реализацию или тесты. Не спрашивай то, на что документ уже отвечает.
- Один вопрос про одно решение. Объединяй дефекты, которые закрываются одним ответом.
- Формулируй закрыто и конкретно, с опорой на текст: «Р-3 ограничивает сумму значением 1 000, а пример \
в таблице использует 500. Какое значение верно?»
- options: 2-3 реалистичных варианта ответа, чтобы заказчику было проще выбрать.
- priority: blocking (без ответа нельзя начинать разработку или писать тесты), important, nice.
- addressee: кому задать.
- why: что сломается или останется неизвестным без ответа.
- Отсортируй: сначала blocking. Обычно получается 8-15 вопросов.

Подтверждённые дефекты:
{findings_block}

Документ (номер строки | текст):
<document>
{numbered_doc}
</document>
"""


def final(numbered_doc: str, stats: str, decision: str, findings_block: str) -> str:
    return f"""\
Задача: по подтверждённым дефектам подготовь (1) вопросы для уточнения и (2) итог ревью.

Часть 1. questions: вопросы, которые аналитик должен задать заказчику и смежным командам до старта разработки.
- Задавай вопрос только если ответ меняет реализацию или тесты. Не спрашивай то, на что документ уже отвечает.
- Один вопрос про одно решение. Объединяй дефекты, которые закрываются одним ответом.
- Формулируй закрыто и конкретно, с опорой на текст: «Р-3 ограничивает сумму значением 1 000, а пример \
в таблице использует 500. Какое значение верно?»
- options: 2-3 реалистичных варианта ответа, чтобы заказчику было проще выбрать.
- priority: blocking (без ответа нельзя начинать разработку или писать тесты), important, nice.
- addressee: кому задать. why: что сломается или останется неизвестным без ответа.
- quote: дословный фрагмент документа. finding_ids и req_ids: связанные находки и требования.
- Сначала blocking. Обычно получается 8-15 вопросов.

Часть 2. Итог. Решение по готовности уже принято правилом и не может быть изменено:
{decision}

Статистика: {stats}

- development_rationale: 2-3 предложения, почему по документу можно или нельзя начинать разработку, со ссылками на ID находок.
- testing_rationale: 2-3 предложения про готовность к проектированию тестов.
- fix_first: 5-7 пунктов в порядке очерёдности: что исправить в первую очередь, с ID находок и конкретным действием.
- overall: 2-4 предложения общего вывода о качестве документа.

Подтверждённые дефекты:
{findings_block}

Документ (номер строки | текст):
<document>
{numbered_doc}
</document>
"""


def conclusion(stats: str, decision: str, findings_block: str) -> str:
    return f"""\
Задача: сформулируй итог ревью.

Решение по готовности уже принято правилом и не может быть изменено:
{decision}

Статистика:
{stats}

Подтверждённые дефекты (critical и major):
{findings_block}

Верни:
- development_rationale: 2-3 предложения, почему по документу можно или нельзя начинать разработку, со ссылками на ID находок.
- testing_rationale: 2-3 предложения про готовность к проектированию тестов.
- fix_first: 5-7 пунктов в порядке очерёдности: что исправить в первую очередь, с ID находок и конкретным действием.
- overall: 2-4 предложения общего вывода о качестве документа.
"""
