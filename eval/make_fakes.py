def _runs(par, text: str) -> None:
    """**жирный** и `код` внутри строки."""
    from docx.shared import Pt

    for part in re.split(r"(\*\*[^*]+\*\*|`[^`]+`)", text):
        if not part:
            continue
        if part.startswith("**"):
            par.add_run(part[2:-2]).bold = True
        elif part.startswith("`"):
            r = par.add_run(part[1:-1])
            r.font.name = "Consolas"
            r.font.size = Pt(9)
        else:
            par.add_run(part)


def write_docx(md: str, path: Path) -> None:
    import docx

    d = docx.Document()
    lines = md.split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i].rstrip()
        if ln.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                    rows.append(cells)
                i += 1
            t = d.add_table(rows=len(rows), cols=len(rows[0]))
            t.style = "Table Grid"
            for r, cells in enumerate(rows):
                for c, val in enumerate(cells):
                    cell = t.cell(r, c)
                    cell.text = ""
                    _runs(cell.paragraphs[0], val)
                    if r == 0:
                        for run in cell.paragraphs[0].runs:
                            run.bold = True
            continue
        m = re.match(r"^(#{1,4}) (.*)", ln)
        if m:
            d.add_heading(m.group(2), level=len(m.group(1)))
        elif re.match(r"^\* ", ln):
            _runs(d.add_paragraph(style="List Bullet"), ln[2:])
        elif re.match(r"^\d+\. ", ln):
            _runs(d.add_paragraph(style="List Number"), re.sub(r"^\d+\. ", "", ln))
        elif ln and ln != "---":
            _runs(d.add_paragraph(), ln.strip())
        i += 1
    d.save(str(path))


def write_pdf(md: str, path: Path) -> None:
    import markdown
    import pymupdf as fitz

    html = markdown.markdown(md, extensions=["tables", "fenced_code"])
    css = """
    @font-face { font-family: Doc; src: url(arial.ttf); }
    @font-face { font-family: Doc; src: url(arialbd.ttf); font-weight: bold; }
    body { font-family: Doc; font-size: 10pt; }
    h1 { font-size: 17pt; } h2 { font-size: 14pt; } h3 { font-size: 12pt; } h4 { font-size: 11pt; }
    table { border-collapse: collapse; width: 100%; }
    th, td { border: 1px solid #888; padding: 2px 4px; font-size: 9pt; }
    code { font-family: Doc; font-size: 8.5pt; }
    """
    story = fitz.Story(html=html, user_css=css, archive=fitz.Archive("C:/Windows/Fonts"))
    writer = fitz.DocumentWriter(str(path))
    page = fitz.paper_rect("a4")
    where = page + (50, 50, -50, -50)
    more = True
    while more:
        dev = writer.begin_page(page)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()


